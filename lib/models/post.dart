class Post {
  final String userImg;
  final String user;
  final String img;
  final String text;
  final String time;
  final int likes;
  final int comments;
  final int shares;

  Post({
    required this.userImg,
    required this.user,
    required this.img,
    required this.text,
    required this.time,
    required this.likes,
    required this.comments,
    required this.shares,
  });
}